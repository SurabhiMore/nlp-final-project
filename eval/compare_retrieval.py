"""Compare two retrieval result files and write a before/after report.

    python -m eval.compare_retrieval \
        --set "Main questions" eval/results/retrieval_baseline.json eval/results/retrieval_results.json \
        --set "Held-out questions" eval/results/retrieval_baseline_heldout.json eval/results/retrieval_results_heldout.json \
        --out eval/results/retrieval_comparison.md

Each --set compares the same questions before and after a change. The report gives
Hit@1, Hit@5, Recall@5 and MRR@10 for every exhibit separately, and lists every
question whose first supporting passage moved, marking regressions explicitly.
"""

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from pipeline import config  # noqa: E402

METRICS = ["hit@1", "hit@5", "hit@8", "recall@5", "mrr@10"]


def _rank(r):
    return r if r is not None else "miss"


def _worse(before, after):
    return (after or 99) > (before or 99)


def compare_set(name, before, after):
    lines = [f"## {name}", ""]
    regressions = 0
    for exhibit in sorted(set(before["exhibits"]) | set(after["exhibits"])):
        b, a = before["exhibits"].get(exhibit), after["exhibits"].get(exhibit)
        if not b or not a:
            lines += [f"### {exhibit}", "", "Only in one of the two runs; not compared.", ""]
            continue
        b_ids = [q["id"] for q in b["questions"]]
        a_ids = [q["id"] for q in a["questions"]]
        if sorted(b_ids) != sorted(a_ids):
            raise ValueError(f"{name} / {exhibit}: the two runs do not use the same questions")
        lines += [f"### {exhibit} ({b['summary']['questions']} questions)", "",
                  "| Metric | Before | After | Change |", "|---|---|---|---|"]
        for m in METRICS:
            x, y = b["summary"][m], a["summary"][m]
            lines.append(f"| {m} | {x:.3f} | {y:.3f} | {y - x:+.3f} |")
        lines.append("")
        b_rank = {q["id"]: q["first_hit_rank"] for q in b["questions"]}
        moved = []
        for q in a["questions"]:
            before_rank, after_rank = b_rank[q["id"]], q["first_hit_rank"]
            if (before_rank or 99) != (after_rank or 99):
                worse = _worse(before_rank, after_rank)
                regressions += worse
                moved.append(f"| {q['id']} | {q['question']} | {_rank(before_rank)} | {_rank(after_rank)} | "
                             f"{'**regression**' if worse else 'better'} |")
        if moved:
            lines += ["Questions whose first supporting passage moved:", "",
                      "| ID | Question | Rank before | Rank after | |", "|---|---|---|---|---|", *moved, ""]
        else:
            lines += ["No question changed rank.", ""]
    return lines, regressions


def main():
    parser = argparse.ArgumentParser(description="Before/after report for two retrieval runs.")
    parser.add_argument("--set", nargs=3, action="append", required=True,
                        metavar=("NAME", "BEFORE", "AFTER"), help="a name and two retrieval result files")
    parser.add_argument("--out", help="write the report here (default: print it)")
    args = parser.parse_args()

    lines = ["# Retrieval: before vs after", "",
             "Generated by `python -m eval.compare_retrieval`. Ranks are the rank of the first "
             "supporting passage in the top 10 (\"miss\" = not in the top 10).", ""]
    total = 0
    for name, before_path, after_path in args.set:
        before = json.loads(Path(before_path).read_text(encoding="utf-8"))
        after = json.loads(Path(after_path).read_text(encoding="utf-8"))
        lines += [f"Before: `{before_path}` ({before.get('run_at', '?')})  ",
                  f"After: `{after_path}` ({after.get('run_at', '?')})", ""]
        section, regressions = compare_set(name, before, after)
        lines += section
        total += regressions
    lines += [f"**Regressions in total: {total}.**", ""]
    report = "\n".join(lines)
    if args.out:
        Path(args.out).write_text(report, encoding="utf-8")
        print(f"Saved to {Path(args.out).resolve().relative_to(config.ROOT)} ({total} regressions)")
    else:
        print(report)


if __name__ == "__main__":
    main()
